#!/usr/bin/env python3
"""Regenerate docs/xtest-scoreboard.md from pytest JUnit XML.

One row per test function listed in docs/xtest-coverage.md (plus any test the
XML names that the coverage document does not), one column per generated SDK
type. A cell is the worst result of every parametrised case that drives that
type on either side: fail > skip:<reason> > pass; n/a when no case ran.
"""

import argparse
import datetime as dt
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

SDK = Path(__file__).resolve().parent.parent
GC_TYPES = ["gcgo", "gcts", "gcpy", "gcjava", "gccs", "gcrs", "gcc", "gcswift"]
RANK = {"fail": 3, "skip": 2, "pass": 1, "n/a": 0}
MODULE_HEADING = re.compile(r"^## `(test_[a-z0-9_]+\.py)`")
TEST_ROW = re.compile(r"^\| `((?:test_|Test)[A-Za-z0-9_.]+)` \|")
HARNESS_ROW = re.compile(r"^\| `(test_[a-z0-9_]+\.py)` \| `([A-Za-z0-9_.]+)` \|")
REASON_LIMIT = 72


def coverage_rows(path):
    """Test ids in document order: per-module sections list one test per row,
    and the harness unit-test table lists ``module | Class.test``."""
    rows = []
    module = None
    for line in path.read_text().splitlines():
        if heading := MODULE_HEADING.match(line):
            module = heading.group(1)
            continue
        if line.startswith("## "):
            module = None
        if harness := HARNESS_ROW.match(line):
            test = f"{harness.group(1)}::{harness.group(2).replace('.', '::')}"
        elif module and (row := TEST_ROW.match(line)):
            test = f"{module}::{row.group(1).replace('.', '::')}"
        else:
            continue
        if test not in rows:
            rows.append(test)
    return rows


def case_id(case):
    module = case.get("classname", "").split(".")
    name = case.get("name", "")
    base = name.split("[", 1)[0]
    if not module or not module[0]:
        return None, name
    file = module[0] + ".py"
    classes = module[1:]
    return "::".join([file, *classes, base]), name


def case_types(name):
    params = name[name.find("[") + 1 : -1] if "[" in name else ""
    return {t for t in GC_TYPES if re.search(rf"(^|-){re.escape(t)}@", params)}


def case_result(case):
    if case.find("failure") is not None or case.find("error") is not None:
        return "fail", ""
    skipped = case.find("skipped")
    if skipped is not None:
        reason = (skipped.get("message") or skipped.text or "").strip()
        reason = re.sub(r"^Skipped:\s*", "", reason).replace("\n", " ").replace("|", "/")
        if len(reason) > REASON_LIMIT:
            reason = reason[: REASON_LIMIT - 1] + "…"
        return "skip", reason
    return "pass", ""


def collect(xml_paths):
    cells = {}
    for path in xml_paths:
        for case in ET.parse(path).iter("testcase"):
            test, name = case_id(case)
            if test is None:
                continue
            status, reason = case_result(case)
            for t in case_types(name):
                current = cells.get((test, t), ("n/a", ""))
                if RANK[status] > RANK[current[0]]:
                    cells[(test, t)] = (status, reason)
    return cells


def render(rows, cells, sources, label):
    lines = [
        "# xtest scoreboard",
        "",
        f"Generated by `scripts/xtest-scoreboard.py` on {dt.date.today().isoformat()}"
        f" from {', '.join(f'`{s}`' for s in sources)}" + (f" ({label})" if label else "") + ".",
        "One row per test function in [xtest-coverage.md](xtest-coverage.md), one",
        "column per generated SDK type; a cell is the worst result over every",
        "parametrised case that drove that type as encrypt or decrypt SDK:",
        "`pass`, `fail`, `skip:<reason>` or `n/a` when the selection did not run it.",
        "Only the cells the phase targets are run locally; `n/a` elsewhere means",
        "not run in this selection, not unsupported. Harness unit tests stay `n/a`.",
        "",
        "| Test | " + " | ".join(GC_TYPES) + " |",
        "| --- |" + " --- |" * len(GC_TYPES),
    ]
    for row in rows:
        values = []
        for t in GC_TYPES:
            status, reason = cells.get((row, t), ("n/a", ""))
            values.append(f"skip:{reason}" if status == "skip" and reason else status)
        lines.append(f"| `{row}` | " + " | ".join(values) + " |")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("junit", nargs="+", type=Path, help="pytest --junitxml output files")
    parser.add_argument("--coverage", type=Path, default=SDK / "docs/xtest-coverage.md")
    parser.add_argument("--out", type=Path, default=SDK / "docs/xtest-scoreboard.md")
    parser.add_argument("--label", default="", help="free text recorded in the preamble")
    args = parser.parse_args()
    rows = coverage_rows(args.coverage)
    cells = collect(args.junit)
    for test, _ in cells:
        if test not in rows:
            rows.append(test)
    sources = [p.resolve().relative_to(SDK).as_posix() if p.resolve().is_relative_to(SDK) else p.name for p in args.junit]
    args.out.write_text(render(rows, cells, sources, args.label))
    ran = sum(1 for v in cells.values() if v[0] != "n/a")
    print(f"{args.out}: {len(rows)} rows, {ran} cells recorded", file=sys.stderr)


if __name__ == "__main__":
    main()
