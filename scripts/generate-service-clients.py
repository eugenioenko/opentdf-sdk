#!/usr/bin/env python3
"""Generates the host service-client accessors from the reference SDK.

Reads the SDK's service fields (../platform/sdk/sdk.go), their sdkconnect
interfaces and the services' .proto packages, and writes, under <out>:
  go/services.go.in          the sdkconnect interfaces over SDK.Call
  typescript/services.ts.in  Connect-ES clients over the SDK's Transport
  python/services.py.in      the service table the Python clients use
Usage: generate-service-clients.py <platform> <out>
"""
from pathlib import Path
import re
import sys

PLATFORM, OUT = map(Path, sys.argv[1:3])
SDK = PLATFORM/'sdk'
GO_PREFIX = 'github.com/opentdf/platform/protocol/go/'
HEADER = 'Code generated by scripts/generate-service-clients.py from the reference sdkconnect. DO NOT EDIT.'


def words(name):
    return re.findall(r'[A-Z]{2,}s?(?=[A-Z]|$)|[A-Z][a-z0-9]*', name)


def snake(name):
    return '_'.join(w.lower() for w in words(name))


def camel(name):
    w = words(name)
    return w[0].lower() + ''.join(w[1:])


def proto_service(import_path, connect_client):
    rel = import_path[len(GO_PREFIX):]
    name = connect_client[:-len('Client')]
    for proto in sorted((PLATFORM/'service'/rel).glob('*.proto')):
        text = proto.read_text()
        if re.search(r'^service ' + name + r' \{', text, re.M):
            package = re.search(r'^package ([\w.]+);', text, re.M)[1]
            return package + '.' + name, str(proto.relative_to(PLATFORM/'service'))
    raise SystemExit('no service ' + name + ' under ' + rel)


services = []
fields = re.findall(r'^\t(\w+)\s+sdkconnect\.(\w+)$', (SDK/'sdk.go').read_text(), re.M)
for field, interface in fields:
    source = next(p for p in sorted((SDK/'sdkconnect').glob('*.go'))
                  if re.search(r'^type ' + interface + r' interface \{', p.read_text(), re.M))
    text = source.read_text()
    imports = dict((path.rsplit('/', 1)[-1], path) for path in re.findall(r'^\t"(' + re.escape(GO_PREFIX) + r'[\w/]+)"$', text, re.M))
    connect_package, connect_client = re.search(r'(\w+)connect\.New(\w+)\(httpClient', text).groups()
    body = re.search(r'^type ' + interface + r' interface \{\n(.*?)^\}', text, re.M | re.S)[1]
    methods = re.findall(r'^\t(\w+)\(ctx context\.Context, req \*(\w+)\.(\w+)\) \(\*\w+\.(\w+), error\)$', body, re.M)
    import_path = next(path for path in imports.values() if path.endswith('/' + connect_package) or path.rsplit('/', 2)[-2] + path.rsplit('/', 1)[-1] == connect_package)
    full_name, proto = proto_service(import_path, connect_client)
    accessor = {'wellknownConfiguration': 'WellKnown', 'EntityResoution': 'EntityResolution'}.get(field, field)
    services.append({'field': field, 'accessor': accessor, 'interface': interface, 'package': methods[0][1],
                     'import': import_path, 'service': full_name, 'proto': proto, 'methods': methods})

go = ['// ' + HEADER, '', 'package generated', '', 'import (', '\t"context"', '']
for path, package in sorted({(s['import'], s['package']) for s in services}):
    go.append('\t' + package + ' "' + path + '"')
go.append(')')
for s in services:
    impl = s['interface'][0].lower() + s['interface'][1:]
    go += ['', '// ' + s['interface'] + ' is the reference sdkconnect.' + s['interface'] + ' for ' + s['service'] + '.',
           'type ' + s['interface'] + ' interface {']
    for method, package, request, response in s['methods']:
        go.append('\t' + method + '(ctx context.Context, req *' + package + '.' + request + ') (*' + package + '.' + response + ', error)')
    go += ['}', '', 'type ' + impl + ' struct{ c serviceCaller }']
    for method, package, request, response in s['methods']:
        go += ['', 'func (c ' + impl + ') ' + method + '(ctx context.Context, req *' + package + '.' + request + ') (*' + package + '.' + response + ', error) {',
               '\tresp := &' + package + '.' + response + '{}',
               '\tif err := c.c.call(ctx, "' + s['service'] + '", "' + method + '", req, resp); err != nil {',
               '\t\treturn nil, err', '\t}', '\treturn resp, nil', '}']
    go += ['', '// ' + s['accessor'] + ' is the reference SDK.' + s['field'] + ': a client of ' + s['service'] + ' over',
           '// the SDK\'s transport. callbacks are passed to every call, as to the SDK\'s other methods.',
           'func (x *SDK) ' + s['accessor'] + '(callbacks ...Callbacks) ' + s['interface'] + ' {',
           '\treturn ' + impl + '{serviceCaller{x, callbacks}}', '}']
    if s['field'] != s['accessor'] and s['field'][0].isupper():
        go += ['', '// ' + s['field'] + ' is ' + s['accessor'] + ' under the reference\'s field name.',
               'func (x *SDK) ' + s['field'] + '(callbacks ...Callbacks) ' + s['interface'] + ' {',
               '\treturn x.' + s['accessor'] + '(callbacks...)', '}']
(OUT/'go').mkdir(parents=True, exist_ok=True)
(OUT/'go/services.go.in').write_text('\n'.join(go) + '\n')

ts = ['// ' + HEADER, "import { createClient, type Client, type Transport } from '@connectrpc/connect';"]
for s in services:
    name = s['service'].rsplit('.', 1)[1]
    alias = s['accessor'] + 'Service'
    ts.append('import { ' + (name if name == alias else name + ' as ' + alias) + ' } from \'./protocol/' + s['proto'][:-len('.proto')] + "_pb.js';")
ts += ['', '/** The platform service clients of the reference SDK, as Connect-ES clients. */', 'export interface PlatformServices {']
for s in services:
    ts.append('  readonly ' + camel(s['accessor']) + ': Client<typeof ' + s['accessor'] + 'Service>;')
ts += ['}', '', 'export function platformServices(transport: Transport): PlatformServices {', '  return {']
for s in services:
    ts.append('    ' + camel(s['accessor']) + ': createClient(' + s['accessor'] + 'Service, transport),')
ts += ['  };', '}']
(OUT/'typescript').mkdir(parents=True, exist_ok=True)
(OUT/'typescript/services.ts.in').write_text('\n'.join(ts) + '\n')

py = ['# ' + HEADER, '"""The platform services of the reference SDK: accessor, module and service."""', '',
      'SERVICES = (']
for s in services:
    module = 'opentdf_tdf3.protocol.' + s['proto'][:-len('.proto')].replace('/', '.') + '_pb2'
    py.append("    ('" + snake(s['accessor']) + "', '" + module + "', '" + s['service'] + "'),")
py.append(')')
(OUT/'python').mkdir(parents=True, exist_ok=True)
(OUT/'python/services.py.in').write_text('\n'.join(py) + '\n')
